// Écrans TV de chaque acte (démo, en sautant les actes depuis le panneau MJ).
import { chromium } from 'playwright';
const shots = new globalThis.URL('../shots/', import.meta.url).pathname;
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1280, height: 764 }, geolocation: { latitude: 48.8566, longitude: 2.3522 }, permissions: ['geolocation'] });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
const click = (t) => p.getByRole('button', { name: t }).first().click();
const view = (v) => p.locator('.demobar .seg button', { hasText: v }).click();
const tab = (t) => p.locator('.mjtabs button', { hasText: t }).click();
const skip = async () => { for (let i = 0; i < 6; i++) { const s = p.getByRole('button', { name: 'Passer', exact: true }); if (await s.count()) await s.click(); await p.waitForTimeout(300); } };
await p.goto('http://localhost:8080/');
await click('Lancer la démo');
await p.waitForTimeout(800);
await tab('Démo');
await click('Placer la zone autour de moi');
await p.waitForTimeout(500);
await view('TV');
await p.waitForTimeout(1200);
await p.screenshot({ path: shots + 't1-accueil.png' });
await view('MJ');
await tab('Nuit');
await click('Lancer l’intro sur la TV');
await view('TV');
await p.waitForTimeout(800);
await p.screenshot({ path: shots + 't2-intro.png' });
await view('MJ');
await click('Lancer la partie');
await click('Lancer la nuit maintenant ?');
await p.waitForTimeout(500);
await click('Passer à l’alerte générale');
await click('Ouvrir le cadenas pour tout le monde ?');
await tab('Démo');
await p.locator('.seg button', { hasText: '×20' }).click();
await p.waitForTimeout(12000);
await view('TV');
await skip();
await p.waitForTimeout(1500);
await p.screenshot({ path: shots + 't3-alerte.png' });
await view('MJ');
await tab('Nuit');
await click('Passer au refuge');
await click('Finir l’alerte maintenant ?');
await view('TV');
await p.waitForTimeout(500);
await skip();
await p.waitForTimeout(1000);
await p.screenshot({ path: shots + 't4-refuge.png' });
await view('MJ');
await click('Terminer la nuit');
await click('Faire partir le dernier portail ?');
await view('TV');
await p.waitForTimeout(500);
await skip();
await p.waitForTimeout(1000);
await p.screenshot({ path: shots + 't5-fin.png' });
console.log(errs.length ? errs.join('\n') : 'aucune erreur');
await b.close();
